# === ANULOMA VILOMA (Prana2) ===
PRANA2_BEGINNER_DESCRIPTION = '''**Anuloma Viloma (Alternate Breathing) for Beginners**

Anuloma Viloma is a technique of alternate breathing through different nostrils.
Translated as "with the direction" (anuloma) and "against" (viloma).

**Features for beginners:**
• Phase duration: inhale - 4 sec, exhale - 4 sec
• No holds for comfortable learning
• Round duration (10 cycles): ~2.5 minutes
• Gentle balance of brain hemispheres

**Execution technique:**
1. Sit comfortably with a straight back
2. Place your left hand on your knee
3. Form Vishnu mudra with your right hand (bend index and middle fingers)
4. Close your right nostril with your thumb, inhale through left for 4 sec
5. Close your left nostril with ring finger, exhale through right for 4 sec
6. Inhale through right for 4 sec, close right nostril
7. Exhale through left for 4 sec
8. This is one cycle. Repeat 10 times.

**Effects:**
• Improves concentration
• Balances left and right hemispheres
• Calms the mind
• Prepares for meditation

**Tip:** Start with 3-5 cycles and gradually increase.'''

PRANA2_ADVANCED_DESCRIPTION = '''**Anuloma Viloma (Alternate Breathing) for Advanced**

Anuloma Viloma is a powerful technique for balancing the Ida and Pingala energy channels.
Full version for experienced practitioners.

**Features for advanced:**
• Phase duration: inhale - 6 sec, exhale - 6 sec
• Holds (kumbhaka) can be added
• Round duration (10 cycles): 4 minutes
• Deep work with the energy system

**Execution technique:**
1. Take a stable asana (Padmasana, Siddhasana, or Sukhasana)
2. Perform Vishnu mudra with your right hand
3. Close your right nostril, inhale through left for 6 sec (with 6 sec hold if desired)
4. Close your left nostril, exhale through right for 6 sec
5. Inhale through right for 6 sec
6. Exhale through left for 6 sec
7. Repeat 10-20 cycles

**Advanced effects:**
• Deep cleansing of nadis (energy channels)
• Balancing the nervous system
• Increased concentration and mental clarity
• Preparation for the higher stages of yoga

**Tip:** Practice in the morning for activation or evening for calming.
Gradually add breath holding (kumbhaka).'''

# === BHRAMARI (Prana3) ===
PRANA3_BEGINNER_DESCRIPTION = '''**Bhramari (Bee Breath) for Beginners**

Bhramari is a calming breathing technique named for the buzzing sound,
reminiscent of a bee's buzz ("bhramari" in Sanskrit means "bee").

**Features for beginners:**
• Phase duration: inhale - 4 sec, exhale with sound - 8 sec
• Gentle effect on the nervous system
• 7 cycles in practice
• Ideal for evening relaxation

**Execution technique:**
1. Sit comfortably with a straight back
2. Close your eyes, relax your face and jaw
3. Gently close your ears with your thumbs
4. Place your index fingers on your forehead, others on the bridge of your nose
5. Take a deep breath in through the nose for 4 seconds
6. On exhalation, produce a soft, steady "MMMMM" sound in the back of the throat
7. Continue the sound exhalation for 8 seconds
8. Repeat 7 times

**Effects:**
• Quickly relieves stress and anxiety
• Calms the mind before sleep
• Lowers blood pressure
• Improves concentration

**Tip:** Practice in the evening after a workday.
The sound should be pleasant, do not strain your throat.'''

PRANA3_ADVANCED_DESCRIPTION = '''**Bhramari (Bee Breath) for Advanced**

Bhramari is a deep vibrational practice that affects the subtle structures of the brain.
Full version for experienced practitioners.

**Features for advanced:**
• Phase duration: inhale - 6 sec, exhale with sound - 12 sec
• More intense vibrational effect
• 7-17 cycles in practice
• Maximum therapeutic effect

**Execution technique:**
1. Take a meditative asana with a straight back
2. Perform Shambhavi mudra (gaze at the third eye)
3. Close your ears with your thumbs, eyes with your index fingers
4. Take a deep, full breath in through the nose for 6 seconds
5. On exhalation, create a steady, continuous vibration "MMMMMM"
6. Continue the exhalation for 12 seconds
7. Feel the vibration in your head, throat, chest
8. Repeat 7-17 times

**Advanced effects:**
• Deep relaxation of the central nervous system
• Reduction of mental activity (ideal for meditation)
• Cleansing of subtle energy channels
• Development of inner awareness

**Tip:** Practice before meditation to deepen the state.
With regular practice, increase the number of cycles to 21.'''

