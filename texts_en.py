# === SAMA VRITTI (Prana1) ===
PRANA1_BEGINNER_DESCRIPTION = '''**Sama Vritti (Equal Breathing) for Beginners**

Sama Vritti is the basic pranayama that begins the journey into breathing practices.
"Sama" means "equal", "Vritti" means "movement" or "wave".

**Features for beginners:**
• Phase duration: inhale - 4 sec, hold - 4 sec, exhale - 4 sec, hold - 4 sec
• Duration of one round (10 cycles): ~2.5 minutes
• Gentle stress on the body
• Ideal for first introduction

**Execution technique:**
1. Take a comfortable sitting position with a straight back
2. Take a deep breath in through the nose for 4 seconds
3. Hold your breath for 4 seconds
4. Exhale fully through the nose for 4 seconds
5. Hold your breath for 4 seconds
6. Repeat the cycle 10 times

**Effects:**
• Calms the nervous system
• Relieves stress and anxiety
• Improves concentration
• Normalizes blood pressure

**Tip:** Practice in a quiet place, focusing on counting.
Do not overexert - breathing should be comfortable.'''

