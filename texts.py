def get_survey_result_with_level(answers):
    """Анализирует ответы и возвращает (result_key, level)"""
    purpose = answers.get("purpose", "calm")
    experience = answers.get("experience", "beginner")
    breathing_type = answers.get("breathing_type", "slow")
    time_of_day = answers.get("time_of_day", "anytime")
    
    if experience == "beginner":
        level = "beginner"
    else:
        level = "advanced"
    
    if purpose == "energy":
        result_key = f"energy_{level}"
    elif purpose == "focus" or breathing_type == "alternate":
        result_key = f"focus_{level}"
    elif breathing_type == "sound" or purpose == "balance" or time_of_day == "evening":
        result_key = "sound_balance"
    elif purpose == "calm" or experience == "beginner":
        result_key = f"calm_{level}"
    else:
        result_key = "default"
    
    return result_key, level

def get_survey_result(answers):
    """Получает результат опросника (для обратной совместимости)"""
    result_key, level = get_survey_result_with_level(answers)
    
    exact_key = f"{result_key}_{level}"
    if exact_key in SURVEY_RESULTS:
        return exact_key
    
    if result_key in SURVEY_RESULTS:
        return result_key
    
    return "default"
